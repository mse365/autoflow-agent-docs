#!/usr/bin/env python3
"""Copy the step pages and specs from the apps that own the steps into this repo.

Every app that adds triggers or actions to AutoFlow keeps the documentation of its own steps
next to its source, in

    <repo-root>/agent-docs/steps/actions/<Name>.md + <Name>.json
    <repo-root>/agent-docs/steps/triggers/<Name>.md + <Name>.json

and hands it to AutoFlow at runtime. This script copies those files into docs/<kind>/ and
spec/<kind>/ of this repo, so agents outside Business Central read the same pages:

- every page gets a "generated" banner as its first line (check_repo.py rejects pages without it),
- specs of apps other than AutoFlow get the "app" key,
- spec/sources.json records which app each step comes from,
- steps an app no longer has are removed – only for the apps given on the command line,
- name and ordinal collisions between apps, and broken spec files, stop the run before anything
  is written,
- finally tools/build_index.py regenerates the indexes and the rule catalog.

Usage:
    python3 tools/sync_step_docs.py --app "AutoFlow=<repo-root>" [--app "<App name>=<repo-root>" ...] [--check]

The app name defaults to the "name" in <repo-root>/app/app.json. --check changes nothing: it prints
what would change and exits 1 if anything would. Standard library only.
"""
from __future__ import annotations

import argparse
import difflib
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build_index  # noqa: E402

BANNER = ("<!-- Generated by tools/sync_step_docs.py from the documentation of the app that owns this step. "
          "Do not edit it here: change the page in the app. -->")
BANNER_PREFIX = "<!-- Generated by tools/sync_step_docs.py"
SOURCES = "spec/sources.json"
BASE_APP = "AutoFlow"  # steps of AutoFlow itself carry no "app" key
KINDS = (("actions", "action"), ("triggers", "trigger"))
REQUIRED = ("kind", "name", "id", "caption", "configuration", "outputs", "rules")
GENERATED = ("docs/actions/README.md", "docs/validation-rules.md", "spec/index.json", SOURCES)


class SyncError(Exception):
    pass


def strip_banner(text):
    if text.startswith(BANNER_PREFIX):
        return text.split("\n", 1)[1] if "\n" in text else ""
    return text


def with_app(spec_text, spec, app):
    """The spec text as published: AutoFlow's verbatim, other apps' with "app" after "category"."""
    if app == BASE_APP:
        if "app" not in spec:
            return spec_text
        spec = {k: v for k, v in spec.items() if k != "app"}
    else:
        if spec.get("app") == app:
            return spec_text
        out = {}
        for k, v in spec.items():
            if k == "app":
                continue
            out[k] = v
            if k == "category":
                out["app"] = app
        if "app" not in out:
            out["app"] = app
        spec = out
    return json.dumps(spec, indent=2, ensure_ascii=False) + "\n"


def read_app(name, root):
    """Read and check one app's step sources. Returns {(folder, Name): (page, spec_text, spec)}."""
    steps_dir = root / "agent-docs" / "steps"
    if not steps_dir.is_dir():
        raise SyncError(f"{name}: {steps_dir} does not exist")
    problems = []
    steps = {}
    for folder, kind in KINDS:
        d = steps_dir / folder
        pages = {f.stem: f for f in d.glob("*.md")} if d.is_dir() else {}
        specs = {f.stem: f for f in d.glob("*.json")} if d.is_dir() else {}
        for n in sorted(set(pages) - set(specs)):
            problems.append(f"{name}: {folder}/{n}.md has no {n}.json")
        for n in sorted(set(specs) - set(pages)):
            problems.append(f"{name}: {folder}/{n}.json has no {n}.md")
        for n in sorted(set(pages) & set(specs)):
            where = f"{name}: {folder}/{n}.json"
            spec_text = specs[n].read_text(encoding="utf-8")
            try:
                spec = json.loads(spec_text)
            except json.JSONDecodeError as e:
                problems.append(f"{where}: not valid JSON ({e})")
                continue
            if not isinstance(spec, dict):
                problems.append(f"{where}: not a JSON object")
                continue
            missing = [k for k in REQUIRED if k not in spec]
            if missing:
                problems.append(f"{where}: missing {missing}")
            if spec.get("kind") != kind:
                problems.append(f"{where}: kind is {spec.get('kind')!r}, expected {kind!r}")
            if spec.get("name") != n:
                problems.append(f"{where}: name is {spec.get('name')!r}, expected {n!r} (the file name)")
            if not isinstance(spec.get("id"), int) or isinstance(spec.get("id"), bool) or spec["id"] < 0:
                problems.append(f"{where}: id must be the step's ordinal (a non-negative integer)")
            page = strip_banner(pages[n].read_text(encoding="utf-8"))
            if "\r" in page or "\r" in spec_text:
                problems.append(f"{name}: {folder}/{n}: CRLF line endings, use LF")
            steps[(folder, n)] = (page, spec_text, spec)
    if problems:
        raise SyncError("\n".join(problems))
    if not steps:
        raise SyncError(f"{name}: no steps found under {steps_dir}")
    return steps


def load_sources(root):
    f = root / SOURCES
    if not f.exists():
        return {folder: {} for folder, _ in KINDS}
    data = json.loads(f.read_text(encoding="utf-8"))
    return {folder: dict(data.get(folder) or {}) for folder, _ in KINDS}


def plan(root, apps):
    """Apply the sync to the tree under root (a scratch copy). Returns the per-kind change list."""
    sources = load_sources(root)
    passed = set(apps)
    problems = []

    # what each passed app brings, with collisions between the passed apps
    new = {folder: {} for folder, _ in KINDS}  # folder -> Name -> (app, page, spec_text, spec)
    for app, steps in apps.items():
        for (folder, n), (page, spec_text, spec) in steps.items():
            if n in new[folder]:
                problems.append(f"{folder}/{n} is provided by both {new[folder][n][0]} and {app}")
                continue
            new[folder][n] = (app, page, spec_text, spec)

    for folder, kind in KINDS:
        # steps that stay: owned by apps not passed, or not owned by any app yet
        kept = {}
        for f in sorted((root / "spec" / folder).glob("*.json")):
            n = f.stem
            owner = sources[folder].get(n)
            if owner in passed or (owner is None and n in new[folder]):
                continue
            kept[n] = (owner, json.loads(f.read_text(encoding="utf-8")).get("id"))
        for n, (app, *_rest, spec) in new[folder].items():
            if n in kept:
                problems.append(f"{folder}/{n} of {app} collides with the step of the same name from {kept[n][0] or 'no app (hand-written)'}")
        by_id = {}
        for n, (owner, sid) in kept.items():
            by_id.setdefault(sid, []).append(f"{n} ({owner or 'no app'})")
        for n, (app, *_rest, spec) in new[folder].items():
            by_id.setdefault(spec.get("id"), []).append(f"{n} ({app})")
        for sid, users in sorted(by_id.items(), key=lambda x: str(x[0])):
            if len(users) > 1:
                problems.append(f"{kind} ordinal {sid} is used by {', '.join(users)}")
    if problems:
        raise SyncError("\n".join(problems))

    changes = {folder: {"added": [], "changed": [], "removed": []} for folder, _ in KINDS}
    for folder, _kind in KINDS:
        # remove steps a passed app no longer has
        for n, owner in sorted(sources[folder].items()):
            if owner in passed and n not in new[folder]:
                for p in (root / "docs" / folder / f"{n}.md", root / "spec" / folder / f"{n}.json"):
                    if p.exists():
                        p.unlink()
                del sources[folder][n]
                changes[folder]["removed"].append(n)
        for n, (app, page, spec_text, spec) in sorted(new[folder].items()):
            md = root / "docs" / folder / f"{n}.md"
            js = root / "spec" / folder / f"{n}.json"
            md_text = BANNER + "\n" + page
            js_text = with_app(spec_text, spec, app)
            existed = md.exists() or js.exists()
            same = (existed and md.exists() and js.exists()
                    and md.read_text(encoding="utf-8") == md_text and js.read_text(encoding="utf-8") == js_text)
            md.parent.mkdir(parents=True, exist_ok=True)
            js.parent.mkdir(parents=True, exist_ok=True)
            md.write_text(md_text, encoding="utf-8", newline="\n")
            js.write_text(js_text, encoding="utf-8", newline="\n")
            sources[folder][n] = app
            if not existed:
                changes[folder]["added"].append(n)
            elif not same:
                changes[folder]["changed"].append(n)

    data = {folder: dict(sorted(sources[folder].items())) for folder, _ in KINDS}
    (root / SOURCES).write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    build_index.build(root)
    return changes


def tracked(root):
    files = set(GENERATED)
    for folder, _ in KINDS:
        files |= {p.relative_to(root).as_posix() for p in (root / "docs" / folder).glob("*.md")}
        files |= {p.relative_to(root).as_posix() for p in (root / "spec" / folder).glob("*.json")}
    return {f for f in files if (root / f).exists()}


def parse_app(value):
    name, sep, path = value.partition("=")
    if not sep:
        name, path = "", value
    root = Path(path).expanduser().resolve()
    if not name:
        manifest = root / "app" / "app.json"
        if not manifest.exists():
            raise SyncError(f"{value}: no app name given and {manifest} does not exist")
        name = json.loads(manifest.read_text(encoding="utf-8-sig")).get("name") or ""
        if not name:
            raise SyncError(f"{manifest} has no name")
    return name.strip(), root


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--app", action="append", required=True, metavar="NAME=REPO_ROOT",
                    help="an app whose agent-docs/steps/ to copy (repeatable); NAME defaults to app/app.json name")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if the sync would change files")
    args = ap.parse_args(argv)

    try:
        apps = {}
        for value in args.app:
            name, root = parse_app(value)
            if name in apps:
                raise SyncError(f"app {name} is given twice")
            apps[name] = read_app(name, root)

        with tempfile.TemporaryDirectory() as tmp:
            scratch = Path(tmp)
            for d in ("docs", "spec"):
                shutil.copytree(ROOT / d, scratch / d)
            changes = plan(scratch, apps)

            before, after = tracked(ROOT), tracked(scratch)
            diffs = []
            for f in sorted(before | after):
                old = (ROOT / f).read_text(encoding="utf-8") if f in before else None
                new = (scratch / f).read_text(encoding="utf-8") if f in after else None
                if old != new:
                    diffs.append((f, old, new))

            for folder, _ in KINDS:
                c = changes[folder]
                print(f"{folder}: {len(c['added'])} added, {len(c['changed'])} changed, {len(c['removed'])} removed")
                for what in ("added", "changed", "removed"):
                    if c[what]:
                        print(f"  {what}: {', '.join(c[what])}")

            if args.check:
                for f, old, new in diffs:
                    print(f"--- {f}: {'added' if old is None else 'removed' if new is None else 'changed'}")
                    if old is not None and new is not None:
                        lines = list(difflib.unified_diff(old.splitlines(), new.splitlines(), f"a/{f}", f"b/{f}", lineterm="", n=1))
                        print("\n".join(lines[:40] + (["  …"] if len(lines) > 40 else [])))
                print(f"{len(diffs)} file(s) would change" if diffs else "up to date")
                return 1 if diffs else 0

            for f, _old, new in diffs:
                target = ROOT / f
                if new is None:
                    target.unlink()
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(new, encoding="utf-8", newline="\n")
            print(f"{len(diffs)} file(s) written or removed")
            return 0
    except SyncError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
